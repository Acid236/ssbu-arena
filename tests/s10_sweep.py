"""S10: STATUS SWEEP by debug injection (SSBU_FIGHTER_DEBUG, fighter_sdk\\fighter_host.c) under the real-call differential.

    python tests/s10_sweep.py gen <variant> <out file> [first last]      only write the command script
    python tests/s10_sweep.py run <tag> <variant> <bin folder> [first last] [KEY=VALUE ...]
    python tests/s10_sweep.py union <module> <report> [<report> ...]     per-name totals over reports (module = lua2cpp_common ...)

variant: ground | air | item | final | mario_ground | mario_air
  for every status kind of the range, for fighter 0 (player 1): put him at the middle of the stage (air: 35 above it,
  situation AIR), request the status through the game's own call, let it run RUN frames, request WAIT (air: FALL),
  REST frames, next. item: the statuses named ITEM_* with an item put in the hand first (three items in turn).
  final: the flag a Smash Ball gives, then the statuses named FINAL*. mario_*: the specials and Mario's own kinds.
`run` starts ONE game at a time (ssbu_s4.exe, tests\\seq_battle.txt: player 1 gets no input), SSBU_FIGHTER_DIFF=1, a
fresh copy of ..\\userdata, never while tests\\QUIET_PLEASE exists (it waits; a run in progress is stopped (own
process only) when the file appears, and is repeated from where it was). A forced status may trap or hang the game:
the kind of the last `[debug] ... status` line is written to tests\\s10_skip_<variant>.txt and the sweep goes on
after it in a new process. Kinds that need a partner (capture, thrown ...) or end the stock are not tried (PRESKIP).
Logs tests\\logs\\s10_sw_<tag>_<n>.log / .report.txt. No game content in this file (names come from the game's own
constant table through fighter_sdk\\tools\\luaconst.py)."""
import os
import re
import shutil
import subprocess
import sys
import time

STUDY = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..'))
sys.path.insert(0, os.path.join(STUDY, 'fighter_sdk', 'tools'))
LOGS = os.path.join(STUDY, 'tests', 'logs')
QUIET = os.path.join(STUDY, 'tests', 'QUIET_PLEASE')
START, RUN, REST = 420, 20, 5
PRESKIP = re.compile(r'DEAD|STANDBY|(^|_)WIN(_|$)|(^|_)LOSE(_|$)|ENTRY|CAPTURE|THROWN|CATCHED|SWALLOWED|BITTEN|CLUNG|SHOULDERED|CATCH_PULL|CATCH_WAIT|CATCH_ATTACK|CATCH_CUT|'
                     r'THROW$|THROW_KIRBY|FINAL|REBIRTH|DEMO|KILLER|SUICIDE|SWIM|(^|_)FLY($|_)')      # SWIM / FLY: trapped in the first runs (3 of 3 tried)


def consts():
    import luaconst
    return {n: v for n, v in luaconst.table_names() if n}


def status_kinds(prefix='FIGHTER_STATUS_KIND_'):
    c = consts()
    return sorted((v, n[len(prefix):]) for n, v in c.items() if n.startswith(prefix) and v < 0x10000 and not n.endswith('_NUM'))


def plan(variant, first=None, last=None, skip=()):
    """-> list of (key, kind value, name, [commands before the request]) in order"""
    c = consts()
    kinds = status_kinds()
    out = []
    if variant in ('ground', 'air'):
        for v, n in kinds:
            if PRESKIP.search(n):
                continue
            out.append(('%d' % v, v, n, []))
    elif variant == 'item':
        for item in ('ITEM_KIND_BEAMSWORD', 'ITEM_KIND_RAYGUN', 'ITEM_KIND_BANANA'):
            for v, n in kinds:
                if 'ITEM' in n and 'CAPTURE' not in n:
                    out.append(('%d/%s' % (v, item), v, n, ['noitem 0', 'item 0 %d' % c[item]]))
    elif variant == 'final':
        for v, n in kinds:
            if 'FINAL' in n and 'DAMAGE' not in n and 'TARGET' not in n and 'CAPTURE' not in n:
                out.append(('%d' % v, v, n, ['final 0']))
    elif variant == 'own':           # S12: the fighter S10_OWN's own kinds (FIGHTER_<NAME>_STATUS_KIND_*), each on the ground and in the air (key + 'a')
        own = status_kinds('FIGHTER_%s_STATUS_KIND_' % os.environ['S10_OWN'].upper())
        for v, n in [(v, n) for v, n in kinds if n.startswith('SPECIAL_')] + own:
            out.append(('%d' % v, v, n, []))
            out.append(('%da' % v, v, n, []))
    elif variant in ('mario_ground', 'mario_air'):
        own = status_kinds('FIGHTER_MARIO_STATUS_KIND_')
        for v, n in [(v, n) for v, n in kinds if n.startswith('SPECIAL_')] + own:
            out.append(('%d' % v, v, n, []))
        out.append(('final', c['FIGHTER_STATUS_KIND_FINAL'], 'FINAL', ['final 0']))
    if first is not None:
        out = [e for e in out if first <= e[1] <= last]
    return [e for e in out if e[0] not in skip]


def script(variant, entries):
    air0 = variant.endswith('air')
    lines = ['# generated by tests/s10_sweep.py: %s, %d kinds' % (variant, len(entries))]
    f = START
    marks = {}
    for key, v, n, pre in entries:
        air = air0 or (variant == 'own' and key.endswith('a'))
        run = 240 if n == 'FINAL' else RUN
        lines.append('# %s %s' % (key, n))
        lines.append('at %d pos 0 0 %s' % (f, '35' if air else '0.1'))
        if air:
            lines.append('at %d air 0 0' % f)
        for p in pre:
            lines.append('at %d %s' % (f, p))
        lines.append('at %d status 0 %d' % (f + 1, v))
        marks[f + 1] = key
        lines.append('at %d status 0 %d' % (f + 1 + run, 14 if air else 0))
        f += 1 + run + REST
    lines.append('at %d damage 0 0' % f)                 # the end marker
    return '\n'.join(lines) + '\n', marks, f


def wait_quiet():
    told = False
    while os.path.exists(QUIET):
        if not told:
            print('   waiting: tests\\QUIET_PLEASE exists', flush=True)
            told = True
        time.sleep(25)


def read(path):
    try:
        with open(path, 'r', errors='replace') as f:
            return f.read()
    except OSError:
        return ''


DBG = re.compile(r'\[debug\] frame (\d+) fighter 0: (\w+)')


def one_run(tag, n, variant, bindir, entries, env_extra):
    """-> (keys done, culprit key or None, verdict)"""
    text, marks, end = script(variant, entries)
    sp = os.path.join(LOGS, 's10_sw_%s_%d.debug.txt' % (tag, n))
    with open(sp, 'w', newline='\n') as f:
        f.write(text)
    wait_quiet()
    ud = os.path.join(STUDY, 'tests', 's10_userdata')
    shutil.rmtree(ud, ignore_errors=True)
    shutil.copytree(os.path.join(STUDY, '..', 'userdata'), ud)
    log = os.path.join(LOGS, 's10_sw_%s_%d.log' % (tag, n))
    rep = os.path.join(LOGS, 's10_sw_%s_%d.report.txt' % (tag, n))
    for p in (log, rep):
        if os.path.exists(p):
            os.remove(p)
    with open(os.path.join(STUDY, 'tests', os.environ.get('S10_SEQ', 'seq_battle.txt'))) as f:
        seq = ' '.join(l.strip() for l in f if not l.startswith('#'))
    env = dict(os.environ)
    env.update(SSBU_SEQ=seq, SSBU_USERDATA=ud, SSBU_FIXED_SEED='1', SSBU_PAIR_WARM='0', SSBU_FIGHTER_REPORT=rep, SSBU_FIGHTER_REPORT_EVERY='200',
               SSBU_REC=os.path.join(LOGS, 's10_input.rec'), SSBU_TRACE=os.path.join(LOGS, 's10_sw_%s_%d.trace.txt' % (tag, n)),
               SSBU_FIGHT_HEALTH='5', SSBU_FIGHTER_DIFF='1', SSBU_FIGHTER_BIN=bindir, SSBU_FIGHTER_DEBUG=sp)
    for kv in env_extra:
        k, v = kv.split('=', 1)
        if v == '(unset)':
            env.pop(k, None)
        else:
            env[k] = v
    t0 = time.time()
    verdict = 'TIMEOUT'
    last_frame, last_change = -1, time.time()
    with open(log, 'w') as out:
        p = subprocess.Popen([os.path.join(STUDY, os.environ.get('S10_EXE', 'ssbu_s4.exe')), os.path.join(STUDY, '..', 'binaries', '13.0.4', 'main.elf'), '1500'],
                             cwd=STUDY, env=env, stdout=out, stderr=subprocess.STDOUT)
        while time.time() - t0 < 1400:
            time.sleep(2)
            text = read(log)
            frames = [int(m.group(1)) for m in DBG.finditer(text)]
            cur = frames[-1] if frames else -1
            if cur != last_frame:
                last_frame, last_change = cur, time.time()
            # tests\QUIET_PLEASE: no game is STARTED while it exists (wait_quiet). A run already started goes on to its
            # end: runs are short (CHUNK kinds, about a minute of fight). First version: stopped the run; with the file
            # coming back every few minutes no run ever finished.
            if 'GUEST TRAP' in text or 'HOST EXCEPTION' in text:
                verdict = 'TRAP'
                break
            if p.poll() is not None:
                verdict = 'EXITED %s' % p.returncode
                break
            if cur >= end:
                verdict = 'DONE'
                time.sleep(2)
                break
            own_mod = os.environ.get('S10_OWN') or 'mario'
            at = text.rfind('fighter source: ' + own_mod)
            if at >= 0 and 'nn::ro::UnloadModule: lua2cpp_' + own_mod in text[at:]:
                verdict = 'MATCH OVER'
                break
            if cur >= 0 and time.time() - last_change > 40:
                verdict = 'STALL'
                break
            if cur < 0 and time.time() - t0 > 420:
                verdict = 'NO FIGHT'
                break
        if p.poll() is None:
            if verdict == 'TRAP':
                try:
                    p.wait(15)
                except subprocess.TimeoutExpired:
                    pass
            if p.poll() is None:
                p.kill()
                p.wait(30)
    text = read(log)
    done, culprit, lastkey = [], None, None
    for m in re.finditer(r'\[debug\] frame (\d+) fighter 0: status', text):
        k = marks.get(int(m.group(1)))
        if k is not None:
            done.append(k)
            lastkey = k
    if verdict in ('TRAP', 'STALL') or verdict.startswith('EXITED'):
        culprit = lastkey
    why = ''
    m = re.search(r'(GUEST TRAP[^\n]*|HOST EXCEPTION[^\n]*)', text)
    if m:
        why = m.group(1)[:160]
    print('   run %d: %s after %.0f s, %d kinds requested, last %s%s' % (n, verdict, time.time() - t0, len(done), lastkey, '  ' + why if why else ''), flush=True)
    return done, culprit, verdict, why


def cmd_run(tag, variant, bindir, first, last, env_extra):
    skipfile = os.path.join(STUDY, 'tests', 's10_skip_%s.txt' % (variant + '_' + os.environ['S10_OWN'] if variant == 'own' else variant))
    skip = {}
    if os.path.exists(skipfile):
        for l in open(skipfile):
            if l.strip():
                skip[l.split()[0]] = l.strip()
    todo = plan(variant, first, last, skip)
    total = len(todo)
    print('%s: %s, %d kinds to request (%d on the skip list)' % (tag, variant, total, len(skip)), flush=True)
    n = 0
    nofight = 0
    chunk = int(os.environ.get('S10_CHUNK', '70'))
    while todo and n < 40:
        n += 1
        done, culprit, verdict, why = one_run(tag, n, variant, bindir, todo[:chunk], env_extra)
        if verdict == 'NO FIGHT':
            nofight += 1
            if nofight >= 2:
                print('   the fight was not reached twice: stopping')
                break
            continue
        if culprit:
            name = [e[2] for e in todo if e[0] == culprit][0]
            with open(skipfile, 'a', newline='\n') as f:
                f.write('%s %s %s: %s\n' % (culprit, name, verdict, why))
            print('   skip list: %s %s (%s)' % (culprit, name, verdict), flush=True)
        gone = set(done) | ({culprit} if culprit else set())
        if verdict in ('QUIET', 'MATCH OVER') and done:
            gone.discard(done[-1])                       # the last one did not get its frames
        todo = [e for e in todo if e[0] not in gone]
        if not gone and verdict != 'NO FIGHT':
            todo = todo[1:]                              # no progress: do not repeat the same first kind for ever
    print('%s: finished, %d of %d kinds not requested' % (tag, len(todo), total))


ROW = re.compile(r'^\s+(\S+)\s+calls\s+(\d+)\s+equal\s+(\d+)\s+equal-interrupted\s+(\d+)\s+differ\s+(\d+)\s+at\s+(0x[0-9a-f]+)(.*)')


def read_report(path, module):
    names = {}
    section = None
    for line in open(path, errors='replace'):
        if line.startswith('module '):
            section = line.split()[1].rstrip(':')
            continue
        if section != module:
            continue
        m = ROW.match(line)
        if m:
            a = names.setdefault(m.group(1), [0, 0, 0, ''])
            a[0] += int(m.group(2))
            a[1] += int(m.group(3)) + int(m.group(4))
            a[2] += int(m.group(5))
            f = re.search(r'first: (.*)', m.group(7))
            if f and not a[3]:
                a[3] = f.group(1).strip()
    return names


def cmd_union(module, paths, out=None):
    tot = {}
    for p in paths:
        names = read_report(p, module)
        print('%-52s names %4d  calls %7d  compared equal %7d  differing calls %5d  names: equal %4d differing %3d never compared %3d' % (
            os.path.basename(p), len(names), sum(v[0] for v in names.values()), sum(v[1] for v in names.values()), sum(v[2] for v in names.values()),
            sum(1 for v in names.values() if v[1] and not v[2]), sum(1 for v in names.values() if v[2]), sum(1 for v in names.values() if not v[1] and not v[2])))
        for k, v in names.items():
            a = tot.setdefault(k, [0, 0, 0, ''])
            a[0] += v[0]
            a[1] += v[1]
            a[2] += v[2]
            a[3] = a[3] or v[3]
    print('UNION %s: names called %d, compared %d, equal on every compared call %d, differing %d, never compared %d' % (
        module, len(tot), sum(1 for v in tot.values() if v[1] or v[2]), sum(1 for v in tot.values() if v[1] and not v[2]),
        sum(1 for v in tot.values() if v[2]), sum(1 for v in tot.values() if not v[1] and not v[2])))
    for k, v in sorted(tot.items()):
        if v[2]:
            print('   DIFFERS %s: calls %d equal %d differ %d first: %s' % (k, v[0], v[1], v[2], v[3][:170]))
    if out:
        with open(out, 'w', newline='\n') as f:
            for k, v in sorted(tot.items()):
                f.write('%s\t%d\t%d\t%d\t%s\n' % (k, v[0], v[1], v[2], v[3]))
    return tot


def main():
    cmd = sys.argv[1]
    if cmd == 'gen':
        nums = [int(a, 0) for a in sys.argv[4:6]] if len(sys.argv) >= 6 else [None, None]
        text, marks, end = script(sys.argv[2], plan(sys.argv[2], nums[0], nums[1]))
        with open(sys.argv[3], 'w', newline='\n') as f:
            f.write(text)
        print('%d kinds, last frame %d' % (len(marks), end))
    elif cmd == 'run':
        rest = sys.argv[5:]
        nums = [int(a, 0) for a in rest if '=' not in a]
        cmd_run(sys.argv[2], sys.argv[3], sys.argv[4], nums[0] if nums else None, nums[1] if len(nums) > 1 else None, [a for a in rest if '=' in a])
    elif cmd == 'union':
        args = [a for a in sys.argv[3:] if not a.startswith('--out=')]
        out = [a[6:] for a in sys.argv[3:] if a.startswith('--out=')]
        cmd_union(sys.argv[2], args, out[0] if out else None)


main()
