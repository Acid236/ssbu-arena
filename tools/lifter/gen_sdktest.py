for block in body.split('Service::Mii::DefaultMii{')[2:] if body.count('Service::Mii::DefaultMii{') > 6 else body.split('Service::Mii::DefaultMii{')[1:]:
    d = {k: int(v) for k, v in re.findall(r'\.(\w+) = (\d+),', block)}
