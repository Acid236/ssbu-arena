def table(name):
    m = re.search(r'constexpr std::array<u8, [^>]*> ' + name + r'\{([^}]*)\}', raw)
    return [int(x, 16) for x in re.findall(r'0x[0-9a-fA-F]+', m.group(1))]
ver3 = {k: table(k) for k in ('Ver3FacelineColorTable', 'Ver3HairColorTable', 'Ver3EyeColorTable', 'Ver3MouthColorTable', 'Ver3GlassColorTable')}

