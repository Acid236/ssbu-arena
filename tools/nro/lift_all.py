"""Assign fixed guest addresses to every NRO and run the lifter copy over all of them.

  python lift_all.py map            write nro_map.json (module -> base, image size, build id, sha256)
  python lift_all.py scan [jobs]    lift every module in memory (nothing written): functions / instructions /
                                    untranslated per module, totals -> lift_scan.txt
  python lift_all.py gen <module> [jobs]   write C for one module into gen_<module>/ at its assigned base
"""
import os, sys, json, subprocess, hashlib, re, time
HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import nro_info

NRO_BASE = 0x7200000000      # 0x7100000000 main image, 0x7300000000 import placeholders, 0x7400000000 host functions
ALIGN = 0x200000             # 2 MB slots keep addresses readable; total stays far below 0x7300000000


def build_map():
    d = os.path.join(HERE, 'nro')
    out = []; base = NRO_BASE
    names = sorted(f for f in os.listdir(d) if f.endswith('.nro'))
    # dependency order first: common, then item, then fighters alphabetically
    names.sort(key=lambda f: (f != 'lua2cpp_common.nro', f != 'lua2cpp_item.nro', f))
    for f in names:
        n = nro_info.Nro(os.path.join(d, f))
        out.append(dict(name=n.name, file=f, base='%#x' % base, image_size=n.image_size, file_size=len(n.d),
                        text_size=n.text_size, bss_start=n.bss_start, bss_end=n.bss_end,
                        build_id=n.build_id[:40], sha256=hashlib.sha256(n.d).hexdigest(),
                        init=n.dyn.get('INIT'), fini=n.dyn.get('FINI')))
        base += (n.image_size + ALIGN - 1) // ALIGN * ALIGN
    json.dump(out, open(os.path.join(HERE, 'nro_map.json'), 'w'), indent=1)
    print('%d modules, %#x .. %#x' % (len(out), NRO_BASE, base))
    return out


def main():
    cmd = sys.argv[1]
    m = build_map()
    if cmd == 'map': return
    if cmd == 'registry':                       # nro_registry.c for nnro_draft.c; optional list of module names to include
        want = set(sys.argv[2:])
        sel = [e for e in m if not want or e['name'] in want]
        with open(os.path.join(HERE, 'nro_registry.c'), 'w') as f:
            f.write('/* generated by lift_all.py registry -- do not edit */\n#include "runtime.h"\n\n')
            f.write('typedef struct NroModule {\n    const char *name; uint64_t base; uint32_t image_size, file_size, bss_start, bss_end;\n'
                    '    uint8_t build_id[20];\n    const FnEntry *fns; int fn_count; const DynSym *syms; int sym_count;\n'
                    '    int loaded; void (**bind_fn)(Ctx *); int *bind_main_import;\n} NroModule;\n\n')
            for e in sel:
                n = e['name']
                f.write('extern const FnEntry fn_table_%s[]; extern const int fn_table_count_%s;\n' % (n, n))
                f.write('extern const DynSym dyn_syms_%s[]; extern const int dyn_sym_count_%s;\n' % (n, n))
            f.write('\n')
            for e in sel:
                n = e['name']
                bid = ', '.join('0x' + e['build_id'][i:i + 2] for i in range(0, 40, 2))
                f.write('NroModule nromod_%s = { "%s", %sULL, %#x, %#x, %#x, %#x, { %s } };\n' % (
                    n, n, e['base'], e['image_size'], e['file_size'], e['bss_start'], e['bss_end'], bid))
            f.write('\nNroModule *const nro_modules[] = {\n' + ''.join('    &nromod_%s,\n' % e['name'] for e in sel) + '};\n')
            f.write('const int nro_module_count = %d;\n\n' % len(sel))
            f.write('/* table pointers are filled at start-up because the counts are not compile-time constants */\n')
            f.write('void nro_registry_init(void) {\n')
            for e in sel:
                n = e['name']
                f.write('    nromod_%s.fns = fn_table_%s; nromod_%s.fn_count = fn_table_count_%s; nromod_%s.syms = dyn_syms_%s; nromod_%s.sym_count = dyn_sym_count_%s;\n' % ((n,) * 8))
            f.write('}\n')
        print('wrote nro_registry.c for %d modules' % len(sel))
        return
    lifter = os.path.join(HERE, 'recomp_nro.py')
    if cmd == 'gen':
        e = next(x for x in m if x['name'] == sys.argv[2])
        jobs = sys.argv[3] if len(sys.argv) > 3 else '8'
        sys.exit(subprocess.call([sys.executable, lifter, 'full', os.path.join(HERE, 'nro', e['file']),
                                  os.path.join(HERE, 'gen_' + e['name']), jobs, e['base']]))
    jobs = sys.argv[2] if len(sys.argv) > 2 else '12'
    tot = [0, 0, 0, 0]; t0 = time.time()
    with open(os.path.join(HERE, 'lift_scan.txt'), 'w') as log:
        for e in m:
            r = subprocess.run([sys.executable, lifter, 'scan', os.path.join(HERE, 'nro', e['file']), jobs, e['base']],
                               capture_output=True, text=True)
            last = [l for l in r.stdout.splitlines() if l.startswith('functions:')]
            if not last:
                log.write('%s FAILED\n%s\n%s\n' % (e['name'], r.stdout[-2000:], r.stderr[-2000:])); print(e['name'], 'FAILED'); continue
            nums = [int(x) for x in re.findall(r': (\d+)', last[0])]
            for i in range(4): tot[i] += nums[i]
            line = '%-22s base %s  functions %6d  instructions %8d  not translated %6d  real code %d' % (
                e['name'], e['base'], nums[0], nums[1], nums[2], nums[3])
            extra = [l for l in r.stdout.splitlines() if l.startswith('  untranslated')]
            log.write(line + '\n' + ''.join(x + '\n' for x in extra)); log.flush()
            print(line)
        line = 'TOTAL functions %d  instructions %d  not translated %d  real code %d  (%.0fs)' % (*tot, time.time() - t0)
        log.write(line + '\n'); print(line)


if __name__ == '__main__':
    main()
